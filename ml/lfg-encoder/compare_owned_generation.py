"""Compare local native greedy byte generation with the owned PyTorch checkpoint."""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess

import torch
from safetensors.torch import load_file

import owned_student


def compare(binary: Path, checkpoint: Path, source: Path, prefix_bytes: int, max_new_bytes: int,
            cpu_threads: int, timeout: float, *, artifact: Path | None = None,
            manifest_sha256: str | None = None, runtime_config: Path | None = None) -> dict:
    if (any(type(value) is not int or value < 1 for value in (prefix_bytes, max_new_bytes, cpu_threads))
            or not math.isfinite(timeout) or timeout <= 0):
        raise ValueError('invalid comparison limits')
    sha = lambda raw: hashlib.sha256(raw).hexdigest()
    manifest_path, weights_path = checkpoint / 'manifest.json', checkpoint / 'weights.safetensors'
    manifest_raw, weights_raw = manifest_path.read_bytes(), weights_path.read_bytes()
    manifest = json.loads(manifest_raw)
    if (sha(weights_raw) != manifest['weights_sha256']
            or sha(Path(owned_student.__file__).read_bytes()) != manifest['code_sha256']['owned_student.py']):
        raise ValueError('checkpoint weights or model code do not match')
    model = owned_student.OwnedByteStudent(manifest['architecture']).eval()
    if prefix_bytes > model.context:
        raise ValueError('source prefix exceeds model context')
    model.load_state_dict(load_file(str(weights_path), device='cpu'))
    torch.set_num_threads(cpu_threads)
    with source.open('rb') as stream:
        prefix = stream.read(prefix_bytes)
    if len(prefix) != prefix_bytes:
        raise ValueError('source is shorter than selected prefix')
    try:
        text = prefix.decode('utf-8')
    except UnicodeDecodeError:
        raise ValueError('source prefix must end at a UTF-8 boundary') from None
    args = [str(binary)]
    if artifact is None:
        if manifest_sha256 is not None:
            raise ValueError('embedded mode does not accept a manifest digest')
        args += ['embedded-owned-byte-generate']
    else:
        if not manifest_sha256 or runtime_config is None:
            raise ValueError('directory mode requires manifest digest and runtime config')
        args += ['owned-byte-generate', '--artifact', str(artifact), '--manifest-sha256', manifest_sha256]
    if runtime_config is not None:
        args += ['--runtime-config', str(runtime_config)]
    args += ['--experimental', '--max-new-bytes', str(max_new_bytes)]
    payload = (json.dumps({'id': 'comparison', 'text': text}, ensure_ascii=False) + '\n').encode('utf-8')
    native = subprocess.run(args, input=payload, capture_output=True, timeout=timeout)
    if native.returncode:
        raise ValueError(f'native generation failed ({native.returncode}): {native.stderr.decode("utf-8", "replace").strip()}')
    response = json.loads(native.stdout)
    if (response.get('schema_version') != 'lfg.owned-byte-generation.v1'
            or response.get('id') != 'comparison' or response.get('input_bytes') != len(prefix)):
        raise ValueError('native generation did not match input')
    expected, context = bytearray(), bytearray(prefix)
    with torch.inference_mode():
        while len(expected) < max_new_bytes and len(context) <= model.context:
            tokens = torch.tensor([list(context)], dtype=torch.long)
            token = int(model(tokens)[0, -1].argmax())
            context.append(token)
            expected.append(token)
    reason = 'byte_limit' if len(expected) == max_new_bytes else 'context_limit'
    if response.get('generated_bytes') != list(expected) or response.get('stop_reason') != reason:
        raise ValueError('native generated bytes or stop reason differ from the source checkpoint')
    if manifest_path.read_bytes() != manifest_raw or weights_path.read_bytes() != weights_raw:
        raise ValueError('checkpoint changed during comparison')
    return {'schema_version': 'lfg.owned-byte-generation-parity.v1', 'binary_sha256': sha(binary.read_bytes()),
            'source_prefix_sha256': sha(prefix), 'checkpoint_manifest_sha256': sha(manifest_raw),
            'prefix_bytes': prefix_bytes, 'generated_bytes': len(expected), 'stop_reason': reason,
            'embedded': artifact is None, 'assessment_quality_checked': False}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('binary', 'checkpoint', 'source'):
        parser.add_argument('--' + name, type=Path, required=True)
    for name in ('prefix-bytes', 'max-new-bytes', 'cpu-threads'):
        parser.add_argument('--' + name, type=int, required=True)
    parser.add_argument('--timeout', type=float, required=True)
    parser.add_argument('--artifact', type=Path)
    parser.add_argument('--manifest-sha256')
    parser.add_argument('--runtime-config', type=Path)
    args = parser.parse_args()
    print(json.dumps(compare(args.binary, args.checkpoint, args.source, args.prefix_bytes,
          args.max_new_bytes, args.cpu_threads, args.timeout, artifact=args.artifact,
          manifest_sha256=args.manifest_sha256, runtime_config=args.runtime_config)))
